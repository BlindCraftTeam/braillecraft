#!/usr/bin/env python3
"""Writes ui-web/tables.js, the menus and dialogs of the web build, from the desktop program's own generated tables,
so the two programs show the same menus and dialogs:

- the menus from crates/bm-desktop/src/menu_table.rs (items, shortcuts after a tab, separators, submenus, check and
  radio items);
- the dialogs from ui-native/dialogs.xrc (titles, sizes, each control's text, place, size, style, default and hidden
  state) and crates/bm-desktop/src/dialog_table.rs (the controls in tab order with their kind).

Run from the repository root: python3 tools/web/make_web_tables.py
"""

import json
import re
import xml.etree.ElementTree as ET

MENU_RS = "crates/bm-desktop/src/menu_table.rs"
DIALOG_RS = "crates/bm-desktop/src/dialog_table.rs"
XRC = "ui-native/dialogs.xrc"
OUT = "ui-web/tables.js"

KINDS = {"Normal": "normal", "Check": "check", "Radio": "radio"}


def rust_string(s):
    return s.encode("latin-1", "backslashreplace").decode("unicode_escape") if "\\" in s else s


def menus():
    text = open(MENU_RS, encoding="utf-8").read()
    consts = {}
    for name, body in re.findall(r"const (M\d+): &\[Entry\] = &\[(.*?)\n\];", text, re.S):
        entries = []
        for line in body.splitlines():
            line = line.strip()
            m = re.match(r'Entry::Item\((\d+), "((?:[^"\\]|\\.)*)", Kind::(\w+)\),', line)
            if m:
                label, _, shortcut = rust_string(m.group(2)).partition("\t")
                entries.append({"id": int(m.group(1)), "label": label, "shortcut": shortcut, "kind": KINDS[m.group(3)]})
            elif line.startswith("Entry::Separator"):
                entries.append({"separator": True})
            else:
                m = re.match(r'Entry::Menu\("((?:[^"\\]|\\.)*)", (M\d+)\),', line)
                if m:
                    entries.append({"label": rust_string(m.group(1)), "menu": m.group(2)})
        consts[name] = entries

    def resolve(entries):
        out = []
        for e in entries:
            if "menu" in e:
                out.append({"label": e["label"], "items": resolve(consts[e["menu"]])})
            else:
                out.append(e)
        return out

    bar = re.search(r"pub const MENU_BAR: &\[\(&str, &\[Entry\]\)\] = &\[(.*?)\n\];", text, re.S).group(1)
    return [{"label": rust_string(label), "items": resolve(consts[m])} for label, m in re.findall(r'\("((?:[^"\\]|\\.)*)", (M\d+)\)', bar)]


def pair(text):
    a, b = text.rstrip("d").split(",")
    return int(a), int(b)


def dialogs():
    order = {}
    text = open(DIALOG_RS, encoding="utf-8").read()
    for rid, w, h, body in re.findall(r"\((\d+), (\d+), (\d+), &\[(.*?)\]\),", text):
        order[int(rid)] = (int(w), int(h), [(int(c), k.lower()) for c, k in re.findall(r"\((\d+), Ctl::(\w+)\)", body)])
    root = ET.parse(XRC).getroot()
    # The file declares the wxWidgets resource namespace; the tags are read by their plain names.
    for el in root.iter():
        el.tag = el.tag.rpartition("}")[2]
    out = {}
    for obj in root:
        name = obj.get("name", "")
        if not name.startswith("dlg"):
            continue
        rid = int(name[3:])
        if rid not in order:
            continue
        w, h, controls = order[rid]
        by_id = {}
        for c in obj:
            cname = c.get("name")
            if cname is None:
                continue
            cid = 1 if cname == "wxID_OK" else 2 if cname == "wxID_CANCEL" else int(cname[1:])
            entry = {"class": c.get("class")}
            for field in ("label", "value", "style"):
                v = c.findtext(field)
                if v is not None:
                    entry[field] = v
            if c.findtext("pos"):
                entry["x"], entry["y"] = pair(c.findtext("pos"))
            if c.findtext("size"):
                entry["w"], entry["h"] = pair(c.findtext("size"))
            entry["default"] = c.findtext("default") == "1"
            entry["hidden"] = c.findtext("hidden") == "1"
            entry["enabled"] = c.findtext("enabled") != "0"
            by_id[cid] = entry
        listed = []
        for cid, kind in controls:
            e = by_id.get(cid)
            if e is None:
                continue
            e = dict(e, id=cid, kind=kind)
            listed.append(e)
        out[rid] = {"title": obj.findtext("title") or "", "w": w, "h": h, "panel": obj.get("class") == "wxPanel", "controls": listed}
    return out


def main():
    data = {"menus": menus(), "dialogs": dialogs()}
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/web/make_web_tables.py from the desktop program's menu and dialog tables; do not edit by hand.\n")
        f.write("export const MENUS = " + json.dumps(data["menus"], ensure_ascii=False, indent=1) + ";\n")
        f.write("export const DIALOGS = " + json.dumps(data["dialogs"], ensure_ascii=False, indent=1) + ";\n")
    print(len(data["menus"]), "menus,", len(data["dialogs"]), "dialogs")


if __name__ == "__main__":
    main()
