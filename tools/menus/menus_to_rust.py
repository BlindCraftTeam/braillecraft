"""Turns a decoded menu resource (menus.txt) and accelerator table (accelerators.txt) into the BrailleCraft menu
bar table (crates/bc-desktop/src/menu_table.rs).

Usage: python3 -I menus_to_rust.py <menus.txt> <accelerators.txt> <out.rs>

Every menu, item, order, access key (&) and command id is kept. An item shows a shortcut, and the shortcut works,
only when the accelerator table binds it: the menu text also names keys the table leaves to the edit control
(Del for Clear) or to Windows (Alt+F4 for Exit), and a wxWidgets menu label with a key in it would take that key
away from the text.
"""
import re
import sys

# Left out: the Macro menu (shown only when macros are defined; the main window shows File Edit View Layout Table
# Document Global Help), Python Options (Python macros), and the licensing, registration and companion-program
# items, which have no counterpart in BrailleCraft.
LEAVE_OUT_MENUS = {"&Macro"}
LEAVE_OUT_IDS = {3110, 3208, 3209, 3212}
RELABEL = {3206: "&New in BrailleCraft 0.1", 3211: "&About BrailleCraft..."}

# Items shown with a check mark. Highlight: "while it is active a check mark (tick mark) appears next to it on the
# Edit menu" (manual, Edit: Highlight). View: "a tick mark (check mark) will appear to the left of some items on this
# menu" (manual, The View Menu); Full-Page, the three fonts (one of them at a time), Six-Key Entry, Codes and
# Translated Line are the settings it lists. Hyphen Table: "Only one table can be selected for any given document"
# (manual, Document: Hyphen Table); shown as a choice group. Translation Tables: the program checks the region in
# force, one of the six (a choice group). Learning Tables: Uncontracted and Fully Contracted are checked by the
# program, with the learning-course items it puts between them, so they are check items rather than a group.
CHECK = {1209, 1301, 1307, 1309, 1310, 2801, 2802}
RADIO = {1303, 1304, 1305, 2701, 2702, 2703, 2704, 2705, 2706, 2901, 2902, 2903, 2904, 2905}

LINE = re.compile(r"^( +)(.*?)(?:\t(.*?))?(?:  \[id (\d+)\])?$")


def rust_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\t", "\\t") + '"'


def main():
    accel = {}
    for raw in open(sys.argv[2], encoding="utf-8"):
        m = re.match(r"^\s+(\S+)\s+-> id (\d+)", raw)
        if m:
            accel[int(m.group(2))] = m.group(1)

    top = []  # (label, entries)
    stack = []  # (indent, entries list)
    skip_indent = None
    for raw in open(sys.argv[1], encoding="utf-8"):
        raw = raw.rstrip("\n")
        if not raw.startswith(" "):
            continue
        m = LINE.match(raw)
        indent = len(m.group(1))
        label, _menu_keys, ident = m.group(2), m.group(3), m.group(4)
        if skip_indent is not None:
            if indent > skip_indent:
                continue
            skip_indent = None
        while stack and stack[-1][0] >= indent:
            stack.pop()
        if indent == 2:
            if label in LEAVE_OUT_MENUS:
                skip_indent = indent
                continue
            entries = []
            top.append((label, entries))
            stack = [(indent, entries)]
            continue
        parent = stack[-1][1]
        if ident is None:
            entries = []
            parent.append(("menu", label, entries))
            stack.append((indent, entries))
        elif label == "----":
            parent.append(("sep",))
        else:
            n = int(ident)
            if n in LEAVE_OUT_IDS:
                continue
            parent.append(("item", n, RELABEL.get(n, label), accel.get(n)))

    def tidy(entries):
        # No separator first, last or doubled once items are left out.
        out = []
        for e in entries:
            if e[0] == "sep" and (not out or out[-1][0] == "sep"):
                continue
            if e[0] == "menu":
                tidy_sub = tidy(e[2])
                e = ("menu", e[1], tidy_sub)
            out.append(e)
        while out and out[-1][0] == "sep":
            out.pop()
        return out

    lines = [
        "// Generated by tools/menus/menus_to_rust.py from the decoded menu resource and accelerator table;",
        "// do not edit by hand.",
        "",
        "use crate::menu::{Entry, Kind};",
        "",
    ]
    counter = [0]

    def emit(entries):
        name = f"M{counter[0]}"
        counter[0] += 1
        body = []
        for e in entries:
            if e[0] == "sep":
                body.append("    Entry::Separator,")
            elif e[0] == "menu":
                sub = emit(e[2])
                body.append(f"    Entry::Menu({rust_str(e[1])}, {sub}),")
            else:
                _, n, label, key = e
                kind = "Check" if n in CHECK else "Radio" if n in RADIO else "Normal"
                text = label + ("\t" + key if key else "")
                body.append(f"    Entry::Item({n}, {rust_str(text)}, Kind::{kind}),")
        lines.append(f"const {name}: &[Entry] = &[")
        lines.extend(body)
        lines.append("];")
        lines.append("")
        return name

    names = [(label, emit(tidy(entries))) for label, entries in top]
    lines.append("/// The menu bar, menus in order.")
    lines.append("pub const MENU_BAR: &[(&str, &[Entry])] = &[")
    for label, name in names:
        lines.append(f"    ({rust_str(label)}, {name}),")
    lines.append("];")
    open(sys.argv[3], "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print(len(names), "menus,", sum(1 for line in lines if "Entry::Item" in line), "items")


if __name__ == "__main__":
    main()
