//! What the Layout menu's code items insert, by command id, and the code vocabulary for Layout, Code List. A pair wraps the selection: the first part before it, the second after it.

pub enum Insert {
    Text(&'static str),
    Pair(&'static str, &'static str),
    /// Taken from the Global, Shortcut Preferences settings or from the document.
    Setting(Dynamic),
}

pub enum Dynamic {
    Grade0,
    Cbc,
    FlushRightLeader,
    NewPage,
    NewReferencePage,
    TerminationSign,
    HardSpace,
}

pub fn insert(id: i32) -> Option<Insert> {
    use Insert::*;
    Some(match id {
        // Translation Codes
        1701 => Setting(Dynamic::Grade0),
        1702 => Text("[tx][g1]"),
        1703 => Text("[tx][g2]"),
        1704 => Setting(Dynamic::Cbc),
        1705 => Text("[g1][fl-span]"),
        1706 => Text("[g1][fl-lifg]"),
        // Character Codes
        1801 => Text("&+"),
        1802 => Setting(Dynamic::TerminationSign),
        1803 => Setting(Dynamic::HardSpace),
        1804 => Pair("[:]", "[;]"),
        // Line Codes
        1901 => Text("[l]"),
        1902 => Text("[sk1]"),
        1903 => Text("[skn]"),
        1904 => Pair("[hds]", "[hde]"),
        1905 => Text("[fr]"),
        1906 => Setting(Dynamic::FlushRightLeader),
        1907 => Text("[l][run]"),
        1908 => Text("[svsbl0]"),
        1909 => Text("[svsbl1]"),
        1910 => Text("[p]"),
        // Left Margin 1 2 3 4 5 7 9 11 13
        2001 => Text("[ind1]"),
        2002 => Text("[ind2]"),
        2003 => Text("[ind3]"),
        2004 => Text("[ind4]"),
        2005 => Text("[ind5]"),
        2006 => Text("[ind7]"),
        2007 => Text("[ind9]"),
        2008 => Text("[ind11]"),
        2009 => Text("[ind13]"),
        // Right Margin 0 1 2 4 6
        2101 => Text("[rm0]"),
        2102 => Text("[rm1]"),
        2103 => Text("[rm2]"),
        2104 => Text("[rm4]"),
        2105 => Text("[rm6]"),
        // Runover Offset 0 1 2 3 4 5 6 8 10
        2201 => Text("[ptye]"),
        2202 => Text("[ptys1]"),
        2203 => Text("[ptys2]"),
        2204 => Text("[ptys3]"),
        2205 => Text("[ptys4]"),
        2206 => Text("[ptys5]"),
        2207 => Text("[ptys6]"),
        2208 => Text("[ptys8]"),
        2209 => Text("[ptys10]"),
        // Math Codes
        2301 => Pair("[tcs]", "[tce]"),
        2302 => Pair("[ts]", "[te]"),
        2304 => Pair("[bs]", "[be]"),
        2305 => Pair("[ps]", "[pe]"),
        2306 => Text("[e]"),
        2307 => Pair("[us]", "[ue]"),
        2308 => Pair("[os]", "[oe]"),
        2310 => Pair("[fs]", "[fl][fe]"),
        2311 => Pair("[sqrts]", "[sqrte]"),
        2312 => Pair("[ixrts]", "[ixrtd][ixrte]"),
        2314 => Text("[i]"),
        2315 => Text("[ii]"),
        2316 => Pair("[fts~b]", "[fte~b]"),
        2317 => Pair("[fts~i]", "[fte~i]"),
        2318 => Text("[eqvn]"),
        2319 => Pair("[ons]", "[one]"),
        2320 => Text("[rmn]"),
        2321 => Pair("[ecans]", "[ecane]"),
        2323 => Text("[bar]"),
        2324 => Text("[evb]"),
        2325 => Text("[bline]"),
        2326 => Text("[enclis]"),
        2327 => Text("[nr]"),
        // Page Codes
        2401 => Setting(Dynamic::NewPage),
        2402 => Setting(Dynamic::NewReferencePage),
        2403 => Pair("[kps]", "[kpe]"),
        2404 => Pair("[vcs]", "[vce]"),
        _ => return None,
    })
}

